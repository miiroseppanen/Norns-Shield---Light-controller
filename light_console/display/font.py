CELL_W = 6
CELL_H = 8
GLYPH_W = 5
GLYPH_H = 7


def _unpack(packed: int) -> tuple[int, ...]:
    rows = []
    for i in range(7):
        rows.append((packed >> (8 * (6 - i))) & 0x1F)
    return tuple(rows)


FONT: dict[str, tuple[int, ...]] = {ch: _unpack(val) for ch, val in _RAW.items()}


def glyph(ch: str) -> tuple[int, ...]:
    key = ch.upper() if ch.isalpha() else ch
    return FONT.get(key, FONT["?"])
